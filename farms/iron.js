// Ферма железа «яма на 3 жителей + зомби в водяной шахте». Схема Фимы из редактора, построена и проверена в выживании (Java 26.3).
// Идея — из видео BasicRedstone. Оси: x — восток, z — юг, y — вверх. Трава — блоки y=−1, ты ходишь по y=0.
// Забор — кольцо x −1…4, z −2…4. Внутри (x 0…3, z −1…3) появляются големы, вода несёт их в угол (0, 3) к лаве.

// вода внутри забора: источник в северо-восточном углу (3, −1), течёт к юго-западному (0, 3)
const water = [['water', 3, 0, -1, { src: true }]];
for (let x = 0; x <= 3; x++) for (let z = -1; z <= 3; z++) {
  if (x === 3 && z === -1) continue;
  water.push(['water', x, 0, z, { flow: z === -1 ? 'w' : x === 3 ? 's' : 'sw' }]);
}
// забор по кругу; клетку над шахтой зомби (4, 0, 1) ставишь в конце, когда зомби уже внизу
const fence = [];
for (let x = -1; x <= 4; x++) for (let z = -2; z <= 4; z++) {
  if ((x === -1 || x === 4 || z === -2 || z === 4) && !(x === 4 && z === 1)) fence.push(['wall', x, 0, z]);
}
// тропинки вокруг: квадрат x −7…10, z −8…10 без забора с тем, что внутри, без сундука и ямки под лаву
const paths = [];
for (let x = -7; x <= 10; x++) for (let z = -8; z <= 10; z++) {
  if (x >= -1 && x <= 4 && z >= -2 && z <= 4) continue;
  if ((x === -1 || x === -2) && z === 5) continue;
  paths.push(['path', x, -1, z]);
}

