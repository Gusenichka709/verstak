const water = [];
for (let x = -2; x <= 4; x++) for (let z = -2; z <= 4; z++) {
  const a = x + 2, b = z + 2;
  if (a === 0 || b === 0) water.push(['water', x, 6, z, { src: true }]);
  else water.push(['water', x, 6, z, { flow: a < b ? 'e' : a > b ? 's' : 'se' }]);
}
// Подвал строится открыто, сверху: котлован 6×5 под северо-западной частью ямы (x −2…3, z −2…2, y 0…5).
// ROOMS — что внутри подвала остаётся пустым (клетки жителей, окна, клетка зомби); всё остальное в рядах 0–2 —
// перегородки из булыжника. Ряды 3–5 закрываются крышей, кроме 4 люков (колодцы до дна ямы).
const ROOMS = [
  [-2, 0, 1, -2, 2, 2], [-2, 0, 0], [3, 0, 1, 3, 2, 2], [3, 0, 0], [1, 0, -2, 2, 2, -2], [0, 0, -2],
  [-1, 0, 0, -1, 2, 1], [-1, 0, 2], [2, 0, 0, 2, 2, 1], [2, 0, 2], [0, 0, -1, 1, 2, -1], [2, 0, -1],
  [0, 0, 0, 1, 1, 1], [0, 2, 0],
];
const HATCH = [[-2, 1], [3, 1], [1, -2], [0, 0]];   // люки: над западной, восточной, северной кроватью и над клеткой зомби
const room = new Set();
for (const b of ROOMS) { const [x1, y1, z1, x2 = x1, y2 = y1, z2 = z1] = b; for (let x = x1; x <= x2; x++) for (let y = y1; y <= y2; y++) for (let z = z1; z <= z2; z++) room.add(`${x},${y},${z}`); }
const walls = [], roof = [];
for (let x = -2; x <= 3; x++) for (let z = -2; z <= 2; z++) {
  for (let y = 0; y <= 2; y++) if (!room.has(`${x},${y},${z}`) && !(y === 2 && x >= 0 && x <= 1 && z >= 0 && z <= 1)) walls.push(['cobble', x, y, z]);
  if (!HATCH.some(([hx, hz]) => hx === x && hz === z)) roof.push(['cobble', x, 3, z, x, 5, z]);
}

