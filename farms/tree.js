// x — восток, z — юг. Саженцы y=0 (z=0), раздатчики за ними (z=1), пыль поверх раздатчиков (y=1), кнопка на западе.

const XS = [0, 2, 4, 6];                     // саженцы через клетку
const HS = [6, 5, 7, 6];                     // берёза вырастает в 5–7 брёвен
const hsh = (x, y, z) => ((x * 73856093) ^ (y * 19349663) ^ (z * 83492791)) >>> 0;

// крона берёзы: два широких слоя (радиус 2) и два узких сверху, углы — как повезёт
const leaves = new Map();
XS.forEach((x0, i) => {
  const top = HS[i] - 1;
  for (let y = top - 2; y <= top + 1; y++) {
    const R = y >= top ? 1 : 2;
    for (let dx = -R; dx <= R; dx++) for (let dz = -R; dz <= R; dz++) {
      const corner = Math.abs(dx) === R && Math.abs(dz) === R;
      if (dx === 0 && dz === 0 && y <= top) continue;                  // там ствол
      if (corner && (y === top + 1 || hsh(x0 + dx, y, dz) % 2)) continue;
      leaves.set(`${x0 + dx},${y},${dz}`, [x0 + dx, y, dz]);
    }
  }
});
const LEAVES = [...leaves.values()];

const P = [.6, 1.3, 2];                       // нажатия кнопки
const GROW = 2, CHOP = 3.6, FALL = 7.4, PLANT = 8.1, END = 10;
const chopAt = (i, j) => CHOP + i * .8 + j * .1;

